#!/bin/sh
# Regenerates ptx_sm20.inc and ptx_sm35.inc from kernels.c with clang's NVPTX backend (LLVM 17 or newer; no CUDA toolkit needed).
#   usage: gen_ptx.sh [clang]        (default: $CLANG, /opt/homebrew/opt/llvm/bin/clang, clang)
# The .version of the PTX is lowered to 3.2 / 4.0 so that the old driver (390, CUDA 9.1 era) accepts it; the kernels only use instructions
# of PTX ISA 3.2 (shfl.down needs sm_30, ld.global.nc sm_32).
set -e
here=$(cd "$(dirname "$0")" && pwd)
CC=${1:-${CLANG:-}}
if [ -z "$CC" ]; then
    if [ -x /opt/homebrew/opt/llvm/bin/clang ]; then CC=/opt/homebrew/opt/llvm/bin/clang; else CC=clang; fi
fi
gen() { # name arch define
    tmp=$(mktemp)
    "$CC" --target=nvptx64-nvidia-cuda -march="$2" -O2 -S -x c -std=gnu11 -ffreestanding -nostdlib -fno-math-errno $3 \
        -Xclang -target-feature -Xclang +ptx32 "$here/kernels.c" -o "$tmp"
    sed -i.bak -e 's/^\.version .*/.version 3.2/' "$tmp" && rm -f "$tmp.bak"
    {
        echo "// generated by kernels/gen_ptx.sh from kernels.c ($2); do not edit"
        echo "static const char * const $1 = R\"PTX("
        cat "$tmp"
        echo ")PTX\";"
    } > "$here/../$4"
    rm -f "$tmp"
    echo "$here/../$4: $(wc -c < "$here/../$4") bytes"
}
gen kPtxSm20 sm_20 "" ptx_sm20.inc
gen kPtxSm35 sm_35 "-DKEPLER" ptx_sm35.inc
