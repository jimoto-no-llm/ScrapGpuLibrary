// hec_gen: a small llama.cpp driver for the hot-expert-cache measurements (docs/plans/HOT_EXPERT_CACHE.md).
//
// It does what llama-bench does for the three standard tests (pp, tg, pg: random tokens `std::rand() % n_vocab`, one fresh context and one warm-up
// per test, `reps` timed runs) and it adds what llama-bench cannot do:
//   * `--moe-cache-mib N` : llama.cpp's own experimental expert cache (llama_context_params.moe_cache_size, src/llama-moe-cache.cpp). llama-bench has
//                           no such option.
//   * `--text FILE`       : natural text. FILE is tokenized, the first --n-prompt tokens are prefilled, then --n-gen tokens are generated by the model
//                           itself (greedy, or --temp T --top-k K with a fixed --seed). The time of llama_decode is reported separately from the time
//                           of the sampler, and the generated text is printed, so that two runs can be compared.
//
// Output: one JSON object per line on stdout, e.g.
//   {"test":"pp512","avg_ts":18.3,"stddev_ts":0.1,"samples_ts":[..]}
//   {"test":"text:foo.txt","n_prompt":120,"pp_ts":33.1,"n_gen":128,"tg_ts":9.8,"tg_total_ts":9.6,"gen":"..."}
//
// Build (tb250):  g++ -O2 -std=c++17 hec_gen.cpp -I$L/include -I$L/ggml/include -L$B -lllama -lggml -lggml-base -Wl,-rpath,$B -o hec_gen
//   L = ~/moe-ep/src/llama.cpp, B = ~/moe-ep/src/llama-build/bin.   (The GGML_BACKEND_PATH plugin, e.g. libggml-cl11.so, is honoured by ggml_backend_load_all.)
//
// HEC_BACKEND_DIR=<dir with libggml-vulkan.so, libggml-cpu.so ..> loads the backends from there (the default is the directory of this executable).
// Devices: `-dev Vulkan0/Vulkan1` (or `none` for CPU only). Experts: `-ncmoe N` (the experts of the first N layers stay on the CPU, as in llama-bench) and
// `-ot REGEX=DEVICE` (any number of times). `-ts a/b/..` tensor split. `-sm layer|none`.

#include "llama.h"
#include "ggml-backend.h"
#include "ggml-cpu.h"

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

static uint64_t now_ns() {
    return std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now().time_since_epoch()).count();
}

static std::vector<std::string> split(const std::string & s, char c) {
    std::vector<std::string> r;
    std::stringstream ss(s);
    std::string x;
    while (std::getline(ss, x, c)) {
        if (!x.empty()) r.push_back(x);
    }
    return r;
}

static void quiet_log(enum ggml_log_level level, const char * text, void *) {
    if (level == GGML_LOG_LEVEL_ERROR || getenv("HEC_GEN_VERBOSE") != nullptr) fputs(text, stderr);
}

static std::string json_escape(const std::string & s) {
    std::string o;
    for (unsigned char c : s) {
        if (c == '"' || c == '\\') { o += '\\'; o += (char) c; }
        else if (c == '\n') o += "\\n";
        else if (c < 0x20) { char b[8]; snprintf(b, sizeof(b), "\\u%04x", c); o += b; }
        else o += (char) c;
    }
    return o;
}

struct bench_ctx {
    llama_context * ctx;
    const llama_vocab * vocab;
    int n_vocab;
    int n_batch;
};

// same draws as llama-bench test_prompt / test_gen
static bool test_prompt(bench_ctx & b, int n_prompt) {
    std::vector<llama_token> tokens(b.n_batch);
    int done = 0;
    while (done < n_prompt) {
        int n = std::min(n_prompt - done, b.n_batch);
        tokens[0] = done == 0 && llama_vocab_get_add_bos(b.vocab) ? llama_vocab_bos(b.vocab) : std::rand() % b.n_vocab;
        for (int i = 1; i < n; i++) tokens[i] = std::rand() % b.n_vocab;
        llama_batch batch = llama_batch_get_one(tokens.data(), n);
        if (llama_decode(b.ctx, batch) != 0) { fprintf(stderr, "decode failed\n"); return false; }
        done += n;
    }
    llama_synchronize(b.ctx);
    return true;
}

static bool test_gen(bench_ctx & b, int n_gen) {
    llama_token token = llama_vocab_get_add_bos(b.vocab) ? llama_vocab_bos(b.vocab) : std::rand() % b.n_vocab;
    for (int i = 0; i < n_gen; i++) {
        llama_batch batch = llama_batch_get_one(&token, 1);
        if (llama_decode(b.ctx, batch) != 0) { fprintf(stderr, "decode failed\n"); return false; }
        llama_synchronize(b.ctx);
        token = std::rand() % b.n_vocab;
    }
    return true;
}

int main(int argc, char ** argv) {
    std::string model, dev_arg, ts_arg, bench, text, sm = "layer";
    std::vector<std::string> ots;
    int ngl = 99, ncmoe = 0, n_thr = 2, n_ub = 512, reps = 3, moe_cache_mib = 0, n_prompt = 128, n_gen = 128, seed = 1234, top_k = 0;
    float temp = 0.0f;
    bool fa = false;
    for (int i = 1; i < argc; i++) {
        std::string a = argv[i];
        auto nx = [&]() { if (i + 1 >= argc) { fprintf(stderr, "missing value for %s\n", a.c_str()); exit(2); } return std::string(argv[++i]); };
        if (a == "-m") model = nx();
        else if (a == "-dev") dev_arg = nx();
        else if (a == "-ngl") ngl = atoi(nx().c_str());
        else if (a == "-ncmoe") ncmoe = atoi(nx().c_str());
        else if (a == "-ot") ots.push_back(nx());
        else if (a == "-ts") ts_arg = nx();
        else if (a == "-sm") sm = nx();
        else if (a == "-t") n_thr = atoi(nx().c_str());
        else if (a == "-ub" || a == "-b") n_ub = atoi(nx().c_str());
        else if (a == "-fa") fa = atoi(nx().c_str()) != 0;
        else if (a == "-r" || a == "--reps") reps = atoi(nx().c_str());
        else if (a == "--moe-cache-mib") moe_cache_mib = atoi(nx().c_str());
        else if (a == "--bench") bench = nx();
        else if (a == "--text") text = nx();
        else if (a == "--n-prompt") n_prompt = atoi(nx().c_str());
        else if (a == "--n-gen") n_gen = atoi(nx().c_str());
        else if (a == "--seed") seed = atoi(nx().c_str());
        else if (a == "--temp") temp = (float) atof(nx().c_str());
        else if (a == "--top-k") top_k = atoi(nx().c_str());
        else { fprintf(stderr, "unknown arg %s\n", a.c_str()); return 2; }
    }
    if (model.empty() || (bench.empty() && text.empty())) {
        fprintf(stderr, "usage: hec_gen -m MODEL [-dev A/B|none] [-ngl N] [-ncmoe N] [-ot RE=DEV].. [-ts a/b] [-t N] [-ub N] [-r REPS] [--moe-cache-mib N]\n"
                        "               (--bench pp512,tg128,pg512:128 | --text FILE --n-prompt N --n-gen M [--seed S] [--temp T --top-k K])\n");
        return 2;
    }

    if (getenv("HEC_BACKEND_DIR") != nullptr) ggml_backend_load_all_from_path(getenv("HEC_BACKEND_DIR")); else ggml_backend_load_all();
    llama_log_set(quiet_log, nullptr);
    llama_backend_init();

    llama_model_params mp = llama_model_default_params();
    mp.n_gpu_layers = ngl;
    mp.split_mode = sm == "none" ? LLAMA_SPLIT_MODE_NONE : LLAMA_SPLIT_MODE_LAYER;
    std::vector<ggml_backend_dev_t> devs;
    if (!dev_arg.empty()) {
        if (dev_arg != "none") {
            for (const auto & n : split(dev_arg, '/')) {
                ggml_backend_dev_t d = ggml_backend_dev_by_name(n.c_str());
                if (!d) { fprintf(stderr, "no device %s\n", n.c_str()); return 1; }
                devs.push_back(d);
            }
        }
        devs.push_back(nullptr);
        mp.devices = devs.data();
    }
    std::vector<float> ts(llama_max_devices(), 0.0f);
    if (!ts_arg.empty()) {
        auto v = split(ts_arg, '/');
        for (size_t i = 0; i < v.size() && i < ts.size(); i++) ts[i] = (float) atof(v[i].c_str());
        mp.tensor_split = ts.data();
    }
    std::vector<std::string> pats;
    std::vector<llama_model_tensor_buft_override> ov;
    pats.reserve(ncmoe + ots.size() + 2);
    for (int i = 0; i < ncmoe; i++) {
        char b[96];
        snprintf(b, sizeof(b), "blk\\.%d\\.ffn_(up|down|gate|gate_up)_(ch|)exps", i);
        pats.push_back(b);
        ov.push_back({ pats.back().c_str(), ggml_backend_cpu_buffer_type() });
    }
    for (const auto & o : ots) {
        const size_t eq = o.rfind('=');
        if (eq == std::string::npos) { fprintf(stderr, "bad -ot %s\n", o.c_str()); return 2; }
        pats.push_back(o.substr(0, eq));
        const std::string dn = o.substr(eq + 1);
        ggml_backend_buffer_type_t bt = nullptr;
        if (dn == "CPU") bt = ggml_backend_cpu_buffer_type();
        else {
            ggml_backend_dev_t d = ggml_backend_dev_by_name(dn.c_str());
            if (!d) { fprintf(stderr, "-ot: no device %s\n", dn.c_str()); return 1; }
            bt = ggml_backend_dev_buffer_type(d);
        }
        ov.push_back({ pats.back().c_str(), bt });
    }
    if (!ov.empty()) {
        ov.push_back({ nullptr, nullptr });
        mp.tensor_buft_overrides = ov.data();
    }
    llama_model * lm = llama_model_load_from_file(model.c_str(), mp);
    if (!lm) { fprintf(stderr, "model load failed\n"); return 1; }
    const llama_vocab * vocab = llama_model_get_vocab(lm);
    const int n_vocab = llama_vocab_n_tokens(vocab);

    ggml_backend_reg_t cpu_reg = ggml_backend_dev_backend_reg(ggml_backend_dev_by_type(GGML_BACKEND_DEVICE_TYPE_CPU));
    auto * tp_new  = (decltype(ggml_threadpool_new) *) ggml_backend_reg_get_proc_address(cpu_reg, "ggml_threadpool_new");
    auto * tp_free = (decltype(ggml_threadpool_free) *) ggml_backend_reg_get_proc_address(cpu_reg, "ggml_threadpool_free");

    auto make_ctx = [&](llama_context *& ctx, ggml_threadpool *& tp) {
        llama_context_params cp = llama_context_default_params();
        cp.n_ctx = std::max(2048, n_ub + 256);
        cp.n_batch = n_ub; cp.n_ubatch = n_ub; cp.n_threads = n_thr; cp.n_threads_batch = n_thr;
        cp.flash_attn_type = fa ? LLAMA_FLASH_ATTN_TYPE_ENABLED : LLAMA_FLASH_ATTN_TYPE_DISABLED;
        cp.moe_cache_size = (size_t) moe_cache_mib * 1024 * 1024;
        ctx = llama_init_from_model(lm, cp);
        if (!ctx) { fprintf(stderr, "context creation failed\n"); exit(1); }
        ggml_threadpool_params tpp = ggml_threadpool_params_default(n_thr);
        tp = tp_new(&tpp);
        llama_attach_threadpool(ctx, tp, nullptr);
    };

    if (!bench.empty()) {
        std::srand(1); // glibc default seed; llama-bench never calls srand
        for (const std::string & t : split(bench, ',')) {
            int pp = 0, tg = 0;
            std::string name = t;
            if (t.rfind("pp", 0) == 0) pp = atoi(t.c_str() + 2);
            else if (t.rfind("tg", 0) == 0) tg = atoi(t.c_str() + 2);
            else if (t.rfind("pg", 0) == 0) { pp = atoi(t.c_str() + 2); const char * c = strchr(t.c_str(), ':'); tg = c ? atoi(c + 1) : 0; }
            else { fprintf(stderr, "bad test %s\n", t.c_str()); return 2; }
            llama_context * ctx; ggml_threadpool * tp;
            make_ctx(ctx, tp);
            bench_ctx b{ ctx, vocab, n_vocab, n_ub };
            llama_memory_clear(llama_get_memory(ctx), false);
            if (pp > 0 && !test_prompt(b, pp)) return 1;      // warm-up, as llama-bench
            if (tg > 0 && !test_gen(b, 1)) return 1;
            std::vector<double> sm_ts;
            for (int r = 0; r < reps; r++) {
                llama_memory_clear(llama_get_memory(ctx), false);
                const uint64_t t0 = now_ns();
                if (pp > 0 && !test_prompt(b, pp)) return 1;
                if (tg > 0 && !test_gen(b, tg)) return 1;
                const double s = (double) (now_ns() - t0) / 1e9;
                sm_ts.push_back((double) (pp + tg) / s);
                fprintf(stderr, "hec_gen: %s rep %d: %.3f t/s\n", t.c_str(), r, sm_ts.back());
            }
            double mean = 0, var = 0;
            for (double v : sm_ts) mean += v;
            mean /= sm_ts.size();
            for (double v : sm_ts) var += (v - mean) * (v - mean);
            const double sd = sm_ts.size() > 1 ? std::sqrt(var / (sm_ts.size() - 1)) : 0.0;
            printf("{\"test\":\"%s\",\"avg_ts\":%.4f,\"stddev_ts\":%.4f,\"samples_ts\":[", name.c_str(), mean, sd);
            for (size_t i = 0; i < sm_ts.size(); i++) printf("%s%.4f", i ? "," : "", sm_ts[i]);
            printf("]}\n");
            fflush(stdout);
            llama_free(ctx);
            tp_free(tp);
        }
    } else {
        std::ifstream f(text, std::ios::binary);
        std::stringstream ss; ss << f.rdbuf();
        const std::string txt = ss.str();
        std::vector<llama_token> tk(txt.size() + 16);
        int nt = llama_tokenize(vocab, txt.c_str(), (int) txt.size(), tk.data(), (int) tk.size(), llama_vocab_get_add_bos(vocab), true);
        if (nt < 0) { fprintf(stderr, "tokenize: need %d\n", -nt); return 1; }
        tk.resize(nt);
        if (nt < n_prompt) { fprintf(stderr, "text has only %d tokens (< %d)\n", nt, n_prompt); n_prompt = nt; }
        tk.resize(n_prompt);
        llama_context * ctx; ggml_threadpool * tp;
        make_ctx(ctx, tp);
        llama_sampler * smpl = llama_sampler_chain_init(llama_sampler_chain_default_params());
        if (temp > 0.0f) {
            if (top_k > 0) llama_sampler_chain_add(smpl, llama_sampler_init_top_k(top_k));
            llama_sampler_chain_add(smpl, llama_sampler_init_temp(temp));
            llama_sampler_chain_add(smpl, llama_sampler_init_dist((uint32_t) seed));
        } else {
            llama_sampler_chain_add(smpl, llama_sampler_init_greedy());
        }
        // one throw-away short run first (shader compilation, first touch of the mapped weights), as the warm-up of llama-bench
        const uint64_t t_pp0 = now_ns();
        for (int o = 0; o < n_prompt; o += n_ub) {
            llama_batch batch = llama_batch_get_one(tk.data() + o, std::min(n_ub, n_prompt - o));
            if (llama_decode(ctx, batch) != 0) { fprintf(stderr, "decode failed\n"); return 1; }
        }
        llama_synchronize(ctx);
        const double t_pp = (double) (now_ns() - t_pp0) / 1e9;
        std::string gen;
        double t_dec = 0.0, t_all = 0.0;
        std::vector<double> per_tok;
        for (int i = 0; i < n_gen; i++) {
            const uint64_t t0 = now_ns();
            llama_token id = llama_sampler_sample(smpl, ctx, -1);
            const uint64_t t1 = now_ns();
            if (llama_vocab_is_eog(vocab, id)) id = tk[std::min<size_t>(tk.size() - 1, 1)]; // keep generating: an end-of-generation token is replaced
            char pc[256];
            int pl = llama_token_to_piece(vocab, id, pc, sizeof(pc), 0, false);
            if (pl > 0) gen.append(pc, pl);
            llama_batch batch = llama_batch_get_one(&id, 1);
            if (llama_decode(ctx, batch) != 0) { fprintf(stderr, "decode failed\n"); return 1; }
            llama_synchronize(ctx);
            const uint64_t t2 = now_ns();
            t_dec += (double) (t2 - t1) / 1e9;
            t_all += (double) (t2 - t0) / 1e9;
            per_tok.push_back((double) (t2 - t1) / 1e6);
        }
        std::string nm = text.substr(text.find_last_of('/') + 1);
        printf("{\"test\":\"text:%s\",\"n_prompt\":%d,\"pp_s\":%.3f,\"pp_ts\":%.4f,\"n_gen\":%d,\"tg_ts\":%.4f,\"tg_total_ts\":%.4f,\"gen\":\"%s\"}\n",
               nm.c_str(), n_prompt, t_pp, n_prompt / t_pp, n_gen, n_gen / t_dec, n_gen / t_all, json_escape(gen).c_str());
        fflush(stdout);
        if (getenv("HEC_GEN_PER_TOKEN")) {
            for (size_t i = 0; i < per_tok.size(); i++) fprintf(stderr, "tok %zu %.2f ms\n", i, per_tok[i]);
        }
        llama_sampler_free(smpl);
        llama_free(ctx);
        tp_free(tp);
    }
    llama_model_free(lm);
    return 0;
}
